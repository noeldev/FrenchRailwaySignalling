using System.Security.Cryptography;
using System.Text;
using Signalling.Schema;
using ValidatorGen.Core;
using ValidatorGen.MapCss;
using static ValidatorGen.MapCss.MapCssSyntax;

namespace ValidatorGen.Generation;

// Writes the validator file: a header naming the sources, the meta block read
// by JOSM and Osmose-QA, then the rules. The version combines the date of the
// newest wiki revision with a hash of the rules, so it only changes when the
// rules do, whenever the generation runs.
public static class ValidatorFileWriter
{
    private const string NewLine = "\r\n";
    private const int HashLength = 8;

    public static string Write(
        string path,
        IReadOnlyList<MapCssRule> rules,
        IReadOnlyList<WikiPage> pages,
        ValidatorSettings settings)
    {
        var body = new StringBuilder();
        foreach (var rule in rules)
        {
            rule.Render(body, NewLine);
        }

        var version = BuildVersion(body.ToString(), pages);

        var output = new StringBuilder();
        output.Append($"/* {settings.Title} - MapCSS validator rules for JOSM and Osmose-QA. */").Append(NewLine);
        output.Append($"/* Generated by {Banner.ProductVersion()} from the OSM wiki. Do not edit by hand. */").Append(NewLine);
        foreach (var page in pages)
        {
            output.Append($"/* Source: {page.Title} ({page.Timestamp.UtcDateTime:yyyy-MM-ddTHH:mm:ssZ}) */").Append(NewLine);
        }

        output.Append(NewLine);
        AppendMeta(output, settings, version);
        output.Append(body);

        var directory = Path.GetDirectoryName(Path.GetFullPath(path));
        if (!string.IsNullOrEmpty(directory))
        {
            Directory.CreateDirectory(directory);
        }

        File.WriteAllText(path, output.ToString().TrimEnd() + NewLine, new UTF8Encoding(false));
        return version;
    }

    private static void AppendMeta(StringBuilder output, ValidatorSettings settings, string version)
    {
        List<string> declarations =
        [
            $"title: {Quote(settings.Title)}",
            $"description: {Quote(settings.Description)}",
            $"version: {Quote(version)}",
            $"author: {Quote(settings.Author)}",
            $"link: {Quote(settings.Link)}",
        ];

        if (!string.IsNullOrWhiteSpace(settings.Icon))
        {
            declarations.Add($"icon: {Quote(settings.Icon)}");
        }

        declarations.Add($"min-josm-version: {settings.MinJosmVersion}");

        if (settings.OsmoseTags.Count > 0)
        {
            declarations.Add($"-osmoseTags: list({string.Join(", ", settings.OsmoseTags.Select(Quote))})");
        }

        new MapCssRule(null, ["meta"], declarations).Render(output, NewLine);
    }

    private static string BuildVersion(string body, IReadOnlyList<WikiPage> pages)
    {
        var newest = pages.Max(page => page.Timestamp).UtcDateTime;
        var hash = Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(body)))[..HashLength];
        return $"{newest:yyyy.MM.dd}-{hash}";
    }
}
